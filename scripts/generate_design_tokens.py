"""Generate Vapour Chrome platform tokens from the canonical JSON source."""
import argparse
import json
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DESIGN = ROOT / "kufr/design-system"
HEADER = "/* Generated by scripts/generate_design_tokens.py; edit tokens.json. */\n"


def validate_tokens(data):
    """Reject malformed or executable CSS before writing any platform output."""
    groups = {"$schemaVersion", "name", "primitives", "themes", "fonts", "typography", "layout", "motion", "reducedMotion"}
    if not isinstance(data, dict) or set(data) != groups or type(data["$schemaVersion"]) is not int or data["$schemaVersion"] != 1 or data["name"] != "Vapour Chrome":
        raise ValueError("Expected Vapour Chrome token schema version 1 and its declared groups.")

    def token_map(value, label):
        if not isinstance(value, dict) or not value:
            raise ValueError(f"{label} must be a nonempty token object.")
        for key, item in value.items():
            if not re.fullmatch(r"[a-z][a-z0-9-]*", key) or not isinstance(item, str) or not item:
                raise ValueError(f"Invalid token {label}.{key}.")
            if re.search(r"[;{}<>@!\\\x00-\x1f\x7f]", item):
                raise ValueError(f"Unsafe CSS in {label}.{key}.")

    def require_keys(value, keys, label):
        if not set(keys).issubset(value):
            raise ValueError(f"Missing required {label} tokens: {sorted(set(keys) - set(value))}")

    primitives = data["primitives"]
    token_map(primitives, "primitives")
    if set(primitives) != {"mist", "midnight", "steel", "periwinkle"}:
        raise ValueError("Expected the four canonical primitive colors.")
    for key, value in primitives.items():
        if not re.fullmatch(r"#[0-9a-fA-F]{6}", value):
            raise ValueError(f"Invalid six-digit primitive color: {key}.")
    if not isinstance(data["themes"], dict) or set(data["themes"]) != {"dark", "light"}:
        raise ValueError("Expected dark and light themes.")
    required_roles = {"void", "surface", "elevated", "ivory", "muted", "accent", "on-accent", "accent-soft", "success", "danger", "warning", "info", "border", "border-subtle", "shadow", "brass", "disabled-foreground", "disabled-background", "viewer-background", "viewer-grid", "viewer-selection", "overlay"}
    for theme, values in data["themes"].items():
        token_map(values, theme)
        if set(values).intersection(primitives):
            raise ValueError("Themes must not override canonical primitive tokens.")
        require_keys(values, required_roles, theme)
        if set(values) != set(data["themes"]["dark"]):
            raise ValueError("Theme token names must match.")
        for key, value in values.items():
            color = re.fullmatch(r"#[0-9a-fA-F]{6}(?:[0-9a-fA-F]{2})?", value)
            reference = re.fullmatch(r"var\(--aw-([a-z][a-z0-9-]*)\)", value)
            shadow = key == "shadow" and re.fullmatch(r"(?:-?\d+(?:\.\d+)?(?:px)? ){3,4}#[0-9a-fA-F]{6}(?:[0-9a-fA-F]{2})?", value)
            if not (color or reference or shadow):
                raise ValueError(f"Invalid semantic color/shadow: {theme}.{key}.")
        combined = {**primitives, **values}
        for key in values:
            seen = set()
            current = key
            while True:
                if current in seen:
                    raise ValueError(f"Cyclic token reference: {theme}.{key}.")
                seen.add(current)
                reference = re.fullmatch(r"var\(--aw-([a-z][a-z0-9-]*)\)", combined[current])
                if not reference:
                    break
                current = reference[1]
                if current not in combined:
                    raise ValueError(f"Unknown token reference: {theme}.{key} -> {current}.")

    fonts = data["fonts"]
    if not isinstance(fonts, list) or len(fonts) != 2:
        raise ValueError("Expected the two self-hosted font declarations.")
    for font in fonts:
        if not isinstance(font, dict) or set(font) != {"family", "file", "weight"}:
            raise ValueError("Invalid font declaration.")
        if not all(isinstance(value, str) for value in font.values()):
            raise ValueError("Font values must be strings.")
        if not re.fullmatch(r"[A-Za-z ]+", font["family"]) or not re.fullmatch(r"[a-z0-9-]+\.ttf", font["file"]):
            raise ValueError("Fonts must use a plain family and local TTF filename.")
        if not re.fullmatch(r"[1-9]00(?: [1-9]00)?", font["weight"]):
            raise ValueError("Invalid font weight.")

    for group in ("typography", "layout", "motion", "reducedMotion"):
        token_map(data[group], group)
    typography = data["typography"]
    require_keys(typography, ["font-display", "font-ui", "font-mono", "text-body", "text-small", "text-title", "text-heading", "text-display"], "typography")
    for key, value in typography.items():
        if key.startswith("font-"):
            valid = re.fullmatch(r"[A-Za-z' ,\-]+", value)
        elif key.startswith("line-"):
            valid = re.fullmatch(r"[1-3](?:\.\d+)?", value)
        elif key.startswith("weight-"):
            valid = re.fullmatch(r"[1-9]00", value)
        elif key.startswith("tracking-"):
            valid = re.fullmatch(r"-?(?:\d*\.)?\d+em", value)
        else:
            valid = re.fullmatch(r"(?:\d*\.)?\d+rem|clamp\(\d*\.?\d+rem, \d*\.?\d+vw, \d*\.?\d+rem\)", value)
        if not valid:
            raise ValueError(f"Invalid typography token: {key}.")
    require_keys(data["layout"], ["touch", "radius-card", "radius-control", "layer-sticky", "layer-overlay", "layer-dialog", "disabled-opacity"], "layout")
    for key, value in data["layout"].items():
        if key.startswith("layer-"):
            valid = re.fullmatch(r"\d+", value)
        elif key == "disabled-opacity":
            valid = re.fullmatch(r"0?\.\d+|0|1", value)
        elif key.startswith("safe-"):
            valid = re.fullmatch(r"env\(safe-area-inset-(?:top|right|bottom|left), 0px\)", value)
        else:
            valid = re.fullmatch(r"\d*\.?\d+(?:px|rem)", value)
        if not valid:
            raise ValueError(f"Invalid layout dimension/layer: {key}.")
    require_keys(data["motion"], ["motion-fast", "motion-normal", "motion-slow", "ease-out"], "motion")
    for key, value in data["motion"].items():
        valid = re.fullmatch(r"\d+ms", value) if key.startswith("motion-") else re.fullmatch(r"cubic-bezier\((?:\d*\.?\d+, ){3}\d*\.?\d+\)", value)
        if not valid:
            raise ValueError(f"Invalid motion token: {key}.")
        if key == "ease-out":
            coordinates = [float(part) for part in value.removeprefix("cubic-bezier(").removesuffix(")").split(", ")]
            if not all(0 <= coordinates[index] <= 1 for index in (0, 2)):
                raise ValueError("Cubic-bezier X coordinates must be between zero and one.")
    if data["reducedMotion"] != {"motion-fast": "0ms", "motion-normal": "0ms", "motion-slow": "0ms"}:
        raise ValueError("Reduced motion must disable every duration.")


def rule(selector, values, indent=""):
    declarations = "\n".join(f"{indent}  --aw-{key}: {value};" for key, value in values.items())
    return f"{indent}{selector} {{\n{declarations}\n{indent}}}\n"


def theme_rule(selector, name, values, indent=""):
    output = rule(selector, values, indent)
    return output.replace("{\n", f"{{\n{indent}  color-scheme: {name};\n", 1)


def outputs(data, root=ROOT):
    validate_tokens(data)
    root = Path(root)
    design = root / "kufr/design-system"
    dark, light = data["themes"]["dark"], data["themes"]["light"]
    palette = HEADER + rule(":root", data["primitives"])
    palette += "\n[data-theme] { color: var(--aw-ivory); }\n\n"
    palette += theme_rule(":root, [data-theme='dark'], [data-theme='system']", "dark", dark)
    palette += "\n" + theme_rule("[data-theme='light']", "light", light)
    palette += "\n@media (prefers-color-scheme: light) {\n"
    palette += theme_rule("[data-theme='system']", "light", light, "  ") + "}\n"
    typography = HEADER
    for font in data["fonts"]:
        typography += ("@font-face {\n"
                       f"  font-family: '{font['family']}';\n"
                       f"  src: url('../fonts/{font['file']}') format('truetype');\n"
                       "  font-style: normal;\n"
                       f"  font-weight: {font['weight']};\n"
                       "  font-display: swap;\n}\n")
    typography += rule(":root", data["typography"])
    motion = HEADER + rule(":root", data["motion"])
    motion += "\n@media (prefers-reduced-motion: reduce) {\n"
    motion += rule(":root", data["reducedMotion"], "  ") + "}\n"
    groups = ["primitives", "themes", "typography", "layout", "motion"]
    module = "// Generated by scripts/generate_design_tokens.py; edit tokens.json.\n"
    module += "const freeze = (value) => { Object.values(value).forEach((item) => { if (item && typeof item === 'object') freeze(item); }); return Object.freeze(value); };\n"
    for group in groups:
        module += f"export const {group} = freeze({json.dumps(data[group], indent=2)});\n"
    module += "export const tokens = Object.freeze({ primitives, themes, typography, layout, motion });\nexport default tokens;\n"
    declaration = "// Generated by scripts/generate_design_tokens.py; edit tokens.json.\n"
    for group in groups:
        declaration += f"export declare const {group}: {typescript_type(data[group])};\n"
    declaration += "export declare const tokens: Readonly<{ primitives: typeof primitives; themes: typeof themes; typography: typeof typography; layout: typeof layout; motion: typeof motion }>;\nexport default tokens;\n"
    names = {"mist": "VapourMist", "midnight": "ChromeMidnight", "steel": "SteelGrey", "periwinkle": "DigitalPeriwinkle"}
    csharp = "// <auto-generated />\n// Source: kufr/design-system/tokens.json\nnamespace Kufr.Backend.Shared;\n\npublic static class DesignTokens\n{\n"
    for key, name in names.items():
        csharp += f'    public const string {name} = "{data["primitives"][key]}";\n'
    csharp += "}\n"
    return {
        design / "tokens/palette.css": palette,
        design / "tokens/typography.css": typography,
        design / "tokens/layout.css": HEADER + rule(":root", data["layout"]),
        design / "tokens/motion.css": motion,
        design / "tokens.mjs": module,
        design / "tokens.d.mts": declaration,
        root / "kufr/backend/Shared/DesignTokens.g.cs": csharp,
    }


def typescript_type(value):
    if isinstance(value, dict):
        return "{ " + " ".join(f"readonly {json.dumps(key)}: {typescript_type(item)};" for key, item in value.items()) + " }"
    return json.dumps(value)


def check(root=ROOT):
    """Return stale generated paths relative to any checkout or test fixture."""
    root = Path(root)
    data = json.loads((root / "kufr/design-system/tokens.json").read_text(encoding="utf-8"))
    return [str(path.relative_to(root)) for path, content in outputs(data, root).items()
            if not path.exists() or path.read_text(encoding="utf-8") != content]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail when committed outputs drift.")
    args = parser.parse_args()
    data = json.loads((DESIGN / "tokens.json").read_text(encoding="utf-8"))
    stale = []
    try:
        generated = outputs(data)
    except ValueError as error:
        parser.error(str(error))
    for path, content in generated.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        print("Generated token drift:\n" + "\n".join(stale))
        return 1
    print("Vapour Chrome tokens are current." if args.check else "Generated Vapour Chrome tokens.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
