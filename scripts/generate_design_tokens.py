"""Generate Vapour Chrome platform tokens from the canonical JSON source."""
import argparse
import json
import re
import xml.etree.ElementTree as ET
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DESIGN = ROOT / "design-system"
HEADER = "/* Generated by scripts/generate_design_tokens.py; edit tokens.json. */\n"
LAUNCH_STORYBOARD = Path("mobilni-aplikace/ios/App/App/Base.lproj/LaunchScreen.storyboard")
INSTALLER_SCRIPT = Path("mobilni-aplikace/scripts/publish-ios-install.py")
INSTALLER_BEGIN = "# BEGIN GENERATED INSTALLER DESIGN"
INSTALLER_END = "# END GENERATED INSTALLER DESIGN"


def read_output(path):
    """Keep IB bytes intact; compare other text with Git's normal newline handling."""
    if path.suffix == ".storyboard":
        return path.read_bytes().decode("utf-8")
    return path.read_text(encoding="utf-8")


def native_launch_background(source, midnight):
    """Own only the launch root's RGB values; Interface Builder owns its XML."""
    try:
        document = ET.fromstring(source)
    except ET.ParseError as error:
        raise ValueError("LaunchScreen.storyboard must remain valid Interface Builder XML.") from error
    if (document.tag != "document" or document.get("launchScreen") != "YES" or
            document.get("type") != "com.apple.InterfaceBuilder3.CocoaTouch.Storyboard.XIB"):
        raise ValueError("Expected an Interface Builder launch-screen document.")
    controllers = document.findall(".//viewController")
    if (len(controllers) != 1 or not document.get("initialViewController") or
            controllers[0].get("id") != document.get("initialViewController")):
        raise ValueError("LaunchScreen.storyboard must have one initial view controller.")
    views = controllers[0].findall("./view[@key='view']")
    backgrounds = document.findall(".//color[@key='backgroundColor']")
    if (len(views) != 1 or not views[0].get("id") or len(backgrounds) != 1 or
            backgrounds[0] not in list(views[0])):
        raise ValueError("LaunchScreen.storyboard must have one root view with one unique background color.")
    background = backgrounds[0]
    if (not all(channel in background.attrib for channel in ("red", "green", "blue")) or
            background.get("alpha") not in ("1", "1.0") or
            background.get("colorSpace") != "custom" or background.get("customColorSpace") != "sRGB"):
        raise ValueError("Launch-screen background must be an opaque custom sRGB color.")

    # Parse for structural authority, then edit the original text to retain IB formatting,
    # comments, IDs, constraints and all attributes outside the three owned channels.
    matches = [match for match in re.finditer(r"<color\b[^<>]*/>", source)
               if re.search(r"\bkey\s*=\s*(['\"])backgroundColor\1", match[0])]
    if len(matches) != 1:
        raise ValueError("Cannot uniquely locate the native background's self-closing color element.")
    match = matches[0]
    color = match[0]
    for channel, offset in (("red", 1), ("green", 3), ("blue", 5)):
        value = str(int(midnight[offset:offset + 2], 16) / 255)
        pattern = rf"(?<![\w:-])({channel}\s*=\s*)(['\"])[^'\"]*\2"
        color, count = re.subn(pattern, lambda found: f"{found[1]}{found[2]}{value}{found[2]}", color)
        if count != 1:
            raise ValueError(f"Cannot uniquely update launch-screen channel: {channel}.")
    source = source[:match.start()] + color + source[match.end():]
    return re.sub(r"(<!--\s*Vapour Chrome dark surface \()#[0-9a-fA-F]{6}(\), no template image\.\s*-->)",
                  lambda found: f"{found[1]}{midnight}{found[2]}", source)


def installer_design_css(design, generated):
    """Inline the canonical CSS for the independently deployed installer script."""
    design = design.resolve()
    computed = {path.resolve(): content for path, content in generated.items()}
    import_pattern = re.compile(r"@import\s+url\(\s*(['\"])([^'\"]+)\1\s*\)\s*;")

    def inline(path, ancestors):
        path = path.resolve()
        if not path.is_relative_to(design) or path.suffix != ".css":
            raise ValueError("Installer stylesheet imports must stay inside the canonical design system.")
        if path in ancestors:
            raise ValueError("Cyclic canonical CSS import while generating installer design.")
        source = computed[path] if path in computed else path.read_text(encoding="utf-8")

        def expand(match):
            relative = match[2]
            if re.search(r"^[a-z][a-z0-9+.-]*:|^[\\/]|[?#]", relative, re.IGNORECASE):
                raise ValueError("Installer stylesheet imports must be relative local CSS paths.")
            return inline(path.parent / relative, ancestors + [path])

        source = import_pattern.sub(expand, source)
        if "@import" in source:
            raise ValueError("Unsupported canonical CSS import syntax in installer design.")
        return source

    css = inline(design / "arcane-workshop.css", [])
    css = re.sub(r"@font-face\s*\{[^{}]*\}\s*", "", css)
    if re.search(r"@font-face|url\s*\(", css, re.IGNORECASE):
        raise ValueError("Standalone installer CSS cannot retain font-face or external asset dependencies.")
    return css.replace("</style", "<\\/style")


def native_installer_design(source, css, midnight, runtime="", controls=""):
    """Replace only the explicit generated block in the editable publisher."""
    lines = source.splitlines(keepends=True)
    begins = [index for index, line in enumerate(lines) if line.rstrip("\r\n") == INSTALLER_BEGIN]
    ends = [index for index, line in enumerate(lines) if line.rstrip("\r\n") == INSTALLER_END]
    if len(begins) != 1 or len(ends) != 1 or begins[0] >= ends[0]:
        raise ValueError("Installer publisher must have one ordered generated-design marker pair.")
    newline = "\r\n" if lines[begins[0]].endswith("\r\n") else "\n"
    block = (f"# Derived from design-system/tokens.json and canonical component CSS.{newline}"
             f"INSTALLER_THEME_COLOR = {midnight!r}{newline}"
             f"INSTALLER_THEME_JS = {runtime!r}{newline}"
             f"INSTALLER_THEME_CONTROLS = {controls!r}{newline}"
             f"INSTALLER_DESIGN_CSS = {css!r}{newline}")
    return "".join(lines[:begins[0] + 1]) + block + "".join(lines[ends[0]:])


def validate_tokens(data):
    """Reject malformed or executable CSS before writing any platform output."""
    groups = {"$schemaVersion", "name", "primitives", "themes", "fonts", "typography", "layout", "motion", "reducedMotion", "themeRegistry", "defaultTheme"}
    if not isinstance(data, dict) or set(data) != groups or type(data["$schemaVersion"]) is not int or data["$schemaVersion"] != 1 or data["name"] != "Vapour Chrome":
        raise ValueError("Expected Vapour Chrome token schema version 1 and its declared groups.")

    def token_map(value, label):
        if not isinstance(value, dict) or not value:
            raise ValueError(f"{label} must be a nonempty token object.")
        for key, item in value.items():
            if not re.fullmatch(r"[a-z][a-z0-9-]*", key) or not isinstance(item, str) or not item:
                raise ValueError(f"Invalid token {label}.{key}.")
            if re.search(r"[;{}<>@!\\\x00-\x1f\x7f]", item):
                raise ValueError(f"Unsafe CSS in {label}.{key}.")

    def require_keys(value, keys, label):
        if not set(keys).issubset(value):
            raise ValueError(f"Missing required {label} tokens: {sorted(set(keys) - set(value))}")

    primitives = data["primitives"]
    token_map(primitives, "primitives")
    if set(primitives) != {"mist", "midnight", "steel", "periwinkle"}:
        raise ValueError("Expected the four canonical primitive colors.")
    for key, value in primitives.items():
        if not re.fullmatch(r"#[0-9a-fA-F]{6}", value):
            raise ValueError(f"Invalid six-digit primitive color: {key}.")
    if not isinstance(data["themes"], dict) or not {"dark", "light", "lord-voldemort"}.issubset(data["themes"]):
        raise ValueError("Expected preserved dark/light palettes and Lord Voldemort.")
    required_roles = {"void", "surface", "elevated", "ivory", "muted", "accent", "on-accent", "accent-soft", "success", "danger", "warning", "info", "border", "border-subtle", "shadow", "brass", "disabled-foreground", "disabled-background", "viewer-background", "viewer-grid", "viewer-selection", "overlay"}
    for theme, values in data["themes"].items():
        token_map(values, theme)
        if set(values).intersection(primitives):
            raise ValueError("Themes must not override canonical primitive tokens.")
        require_keys(values, required_roles, theme)
        if set(values) != set(data["themes"]["dark"]):
            raise ValueError("Theme token names must match.")
        for key, value in values.items():
            color = re.fullmatch(r"#[0-9a-fA-F]{6}(?:[0-9a-fA-F]{2})?", value)
            reference = re.fullmatch(r"var\(--aw-([a-z][a-z0-9-]*)\)", value)
            shadow = key == "shadow" and re.fullmatch(r"(?:-?\d+(?:\.\d+)?(?:px)? ){3,4}#[0-9a-fA-F]{6}(?:[0-9a-fA-F]{2})?", value)
            if not (color or reference or shadow):
                raise ValueError(f"Invalid semantic color/shadow: {theme}.{key}.")
        combined = {**primitives, **values}
        for key in values:
            seen = set()
            current = key
            while True:
                if current in seen:
                    raise ValueError(f"Cyclic token reference: {theme}.{key}.")
                seen.add(current)
                reference = re.fullmatch(r"var\(--aw-([a-z][a-z0-9-]*)\)", combined[current])
                if not reference:
                    break
                current = reference[1]
                if current not in combined:
                    raise ValueError(f"Unknown token reference: {theme}.{key} -> {current}.")

    fonts = data["fonts"]
    if not isinstance(fonts, list) or len(fonts) != 2:
        raise ValueError("Expected the two self-hosted font declarations.")
    for font in fonts:
        if not isinstance(font, dict) or set(font) != {"family", "file", "weight"}:
            raise ValueError("Invalid font declaration.")
        if not all(isinstance(value, str) for value in font.values()):
            raise ValueError("Font values must be strings.")
        if not re.fullmatch(r"[A-Za-z ]+", font["family"]) or not re.fullmatch(r"[a-z0-9-]+\.ttf", font["file"]):
            raise ValueError("Fonts must use a plain family and local TTF filename.")
        if not re.fullmatch(r"[1-9]00(?: [1-9]00)?", font["weight"]):
            raise ValueError("Invalid font weight.")

    for group in ("typography", "layout", "motion", "reducedMotion"):
        token_map(data[group], group)
    registry = data["themeRegistry"]
    if not isinstance(registry, dict) or not {"lord-voldemort", "olivander"}.issubset(registry):
        raise ValueError("Required visual identities are missing.")
    if data["defaultTheme"] != "lord-voldemort":
        raise ValueError("Lord Voldemort must remain the fallback theme.")
    for identifier, definition in registry.items():
        if not re.fullmatch(r"[a-z][a-z0-9-]*", identifier) or not isinstance(definition, dict) or set(definition) != {"label", "palette", "presentation"}:
            raise ValueError("Invalid theme registry entry.")
        if not isinstance(definition["label"], str) or not re.fullmatch(r"[A-Za-z0-9 -]+", definition["label"]):
            raise ValueError("Invalid theme label.")
        if not isinstance(definition["palette"], str) or definition["palette"] not in data["themes"]:
            raise ValueError("Invalid theme label or palette.")
        token_map(definition["presentation"], identifier)
        if set(definition["presentation"]) != set(registry["olivander"]["presentation"]):
            raise ValueError("Presentation roles must match across identities.")
        for value in definition["presentation"].values():
            dimension = r"-?(?:\d*\.)?\d+(?:px|rem|em)"
            if not re.fullmatch(rf"{dimension}(?: {dimension})*|clamp\({dimension}, (?:\d*\.)?\d+vw, {dimension}\)", value):
                raise ValueError("Invalid theme presentation dimension.")
    typography = data["typography"]
    require_keys(typography, ["font-display", "font-ui", "font-mono", "text-body", "text-small", "text-title", "text-heading", "text-display"], "typography")
    for key, value in typography.items():
        if key.startswith("font-"):
            valid = re.fullmatch(r"[A-Za-z' ,\-]+", value)
        elif key.startswith("line-"):
            valid = re.fullmatch(r"[1-3](?:\.\d+)?", value)
        elif key.startswith("weight-"):
            valid = re.fullmatch(r"[1-9]00", value)
        elif key.startswith("tracking-"):
            valid = re.fullmatch(r"-?(?:\d*\.)?\d+em", value)
        else:
            valid = re.fullmatch(r"(?:\d*\.)?\d+rem|clamp\(\d*\.?\d+rem, \d*\.?\d+vw, \d*\.?\d+rem\)", value)
        if not valid:
            raise ValueError(f"Invalid typography token: {key}.")
    require_keys(data["layout"], ["touch", "radius-card", "radius-control", "layer-sticky", "layer-overlay", "layer-dialog", "disabled-opacity"], "layout")
    for key, value in data["layout"].items():
        if key.startswith("layer-"):
            valid = re.fullmatch(r"\d+", value)
        elif key == "disabled-opacity":
            valid = re.fullmatch(r"0?\.\d+|0|1", value)
        elif key.startswith("safe-"):
            valid = re.fullmatch(r"env\(safe-area-inset-(?:top|right|bottom|left), 0px\)", value)
        else:
            valid = re.fullmatch(r"\d*\.?\d+(?:px|rem)", value)
        if not valid:
            raise ValueError(f"Invalid layout dimension/layer: {key}.")
    require_keys(data["motion"], ["motion-fast", "motion-normal", "motion-slow", "ease-out"], "motion")
    for key, value in data["motion"].items():
        valid = re.fullmatch(r"\d+ms", value) if key.startswith("motion-") else re.fullmatch(r"cubic-bezier\((?:\d*\.?\d+, ){3}\d*\.?\d+\)", value)
        if not valid:
            raise ValueError(f"Invalid motion token: {key}.")
        if key == "ease-out":
            coordinates = [float(part) for part in value.removeprefix("cubic-bezier(").removesuffix(")").split(", ")]
            if not all(0 <= coordinates[index] <= 1 for index in (0, 2)):
                raise ValueError("Cubic-bezier X coordinates must be between zero and one.")
    if data["reducedMotion"] != {"motion-fast": "0ms", "motion-normal": "0ms", "motion-slow": "0ms"}:
        raise ValueError("Reduced motion must disable every duration.")


def rule(selector, values, indent=""):
    declarations = "\n".join(f"{indent}  --aw-{key}: {value};" for key, value in values.items())
    return f"{indent}{selector} {{\n{declarations}\n{indent}}}\n"


def theme_rule(selector, name, values, indent=""):
    output = rule(selector, values, indent)
    return output.replace("{\n", f"{{\n{indent}  color-scheme: {name};\n", 1)


def outputs(data, root=ROOT):
    validate_tokens(data)
    root = Path(root)
    design = root / "design-system"
    dark, light = data["themes"]["dark"], data["themes"]["light"]
    palette = HEADER + rule(":root", data["primitives"])
    palette += "\n[data-theme] { color: var(--aw-ivory); }\n\n"
    registry = data["themeRegistry"]
    for identifier, definition in registry.items():
        selector = f"[data-theme='{identifier}']"
        if identifier == data["defaultTheme"]:
            selector = ":root, " + selector
        values = {**data["themes"][definition["palette"]], **definition["presentation"]}
        palette += theme_rule(selector, "dark", values) + "\n"
    palette += theme_rule("[data-theme='dark'], [data-theme='system']", "dark", {**dark, **registry["olivander"]["presentation"]})
    palette += "\n" + theme_rule("[data-theme='light']", "light", {**light, **registry["olivander"]["presentation"]})
    palette += "\n@media (prefers-color-scheme: light) {\n"
    palette += theme_rule("[data-theme='system']", "light", light, "  ") + "}\n"
    typography = HEADER
    for font in data["fonts"]:
        typography += ("@font-face {\n"
                       f"  font-family: '{font['family']}';\n"
                       f"  src: url('../fonts/{font['file']}') format('truetype');\n"
                       "  font-style: normal;\n"
                       f"  font-weight: {font['weight']};\n"
                       "  font-display: swap;\n}\n")
    typography += rule(":root", data["typography"])
    motion = HEADER + rule(":root", data["motion"])
    motion += "\n@media (prefers-reduced-motion: reduce) {\n"
    motion += rule(":root", data["reducedMotion"], "  ") + "}\n"
    groups = ["primitives", "themes", "typography", "layout", "motion", "themeRegistry", "defaultTheme"]
    module = "// Generated by scripts/generate_design_tokens.py; edit tokens.json.\n"
    module += "const freeze = (value) => { Object.values(value).forEach((item) => { if (item && typeof item === 'object') freeze(item); }); return Object.freeze(value); };\n"
    for group in groups:
        module += f"export const {group} = freeze({json.dumps(data[group], indent=2)});\n"
    module += "export const tokens = Object.freeze({ primitives, themes, typography, layout, motion, themeRegistry, defaultTheme });\nexport default tokens;\n"
    declaration = "// Generated by scripts/generate_design_tokens.py; edit tokens.json.\n"
    for group in groups:
        declaration += f"export declare const {group}: {typescript_type(data[group])};\n"
    declaration += "export declare const tokens: Readonly<{ primitives: typeof primitives; themes: typeof themes; typography: typeof typography; layout: typeof layout; motion: typeof motion; themeRegistry: typeof themeRegistry; defaultTheme: typeof defaultTheme }>;\nexport default tokens;\n"
    names = {"mist": "VapourMist", "midnight": "ChromeMidnight", "steel": "SteelGrey", "periwinkle": "DigitalPeriwinkle"}
    csharp = "// <auto-generated />\n// Source: design-system/tokens.json\nnamespace Kufr.Backend.Shared;\n\npublic static class DesignTokens\n{\n"
    for key, name in names.items():
        csharp += f'    public const string {name} = "{data["primitives"][key]}";\n'
    csharp += "}\n"
    runtime = (design / "theme-runtime.js").read_text(encoding="utf-8")

    def background(definition):
        palette = {**data["primitives"], **data["themes"][definition["palette"]]}
        value = palette["void"]
        while reference := re.fullmatch(r"var\(--aw-([a-z][a-z0-9-]*)\)", value):
            value = palette[reference[1]]
        return value

    entries = [{"id": identifier, "label": definition["label"], "background": background(definition)} for identifier, definition in registry.items()]
    runtime = runtime.replace("/* THEME_REGISTRY */", "const themes = " + json.dumps(entries) + ";\n  const defaultTheme = " + json.dumps(data["defaultTheme"]) + ";")
    theme_types = "// Generated by scripts/generate_design_tokens.py; edit tokens.json.\n"
    theme_types += "export type ThemeId = " + " | ".join(json.dumps(identifier) for identifier in registry) + ";\n"
    theme_types += """export declare const themes: readonly Readonly<{ id: ThemeId; label: string; background: string }>[];
export declare const defaultTheme: ThemeId;
export declare function normalizeTheme(value: unknown): ThemeId;
export declare function getTheme(): ThemeId;
export declare function setTheme(value: unknown): ThemeId;
export declare function subscribe(listener: (theme: ThemeId) => void): () => void;
"""
    generated = {
        design / "theme.js": HEADER + runtime,
        design / "theme.d.mts": theme_types,
        design / "tokens/palette.css": palette,
        design / "tokens/typography.css": typography,
        design / "tokens/layout.css": HEADER + rule(":root", data["layout"]),
        design / "tokens/motion.css": motion,
        design / "tokens.mjs": module,
        design / "tokens.d.mts": declaration,
        root / "backend/Shared/DesignTokens.g.cs": csharp,
    }
    storyboard = root / LAUNCH_STORYBOARD
    if storyboard.is_file():
        generated[storyboard] = native_launch_background(read_output(storyboard), data["themes"]["lord-voldemort"]["void"])
    installer = root / INSTALLER_SCRIPT
    if installer.is_file():
        css = installer_design_css(design, generated)
        controls = (design / "theme-controls.js").read_text(encoding="utf-8")
        generated[installer] = native_installer_design(read_output(installer), css, data["themes"]["lord-voldemort"]["void"], HEADER + runtime, controls)
    return generated


def typescript_type(value):
    if isinstance(value, dict):
        return "{ " + " ".join(f"readonly {json.dumps(key)}: {typescript_type(item)};" for key, item in value.items()) + " }"
    return json.dumps(value)


def check(root=ROOT):
    """Return stale generated paths relative to any checkout or test fixture."""
    root = Path(root)
    data = json.loads((root / "design-system/tokens.json").read_text(encoding="utf-8"))
    return [str(path.relative_to(root)) for path, content in outputs(data, root).items()
            if not path.exists() or read_output(path) != content]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="Fail when committed outputs drift.")
    mode.add_argument("--generate", action="store_true", help="Write generated outputs (also the default).")
    args = parser.parse_args()
    data = json.loads((DESIGN / "tokens.json").read_text(encoding="utf-8"))
    stale = []
    try:
        generated = outputs(data)
    except ValueError as error:
        parser.error(str(error))
    for path, content in generated.items():
        if args.check:
            if not path.exists() or read_output(path) != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        print("Generated token drift:\n" + "\n".join(stale))
        return 1
    print("Vapour Chrome tokens are current." if args.check else "Generated Vapour Chrome tokens.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
