"""Generate the firmware choreography from the viewer's same authored score."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
HEADER = ROOT.parents[1] / 'firmware/src/features/physical_effects/PresentationScore.h'


def generate():
    score = json.loads((ROOT / 'effects.json').read_text(encoding='utf-8'))
    lines = ['// Generated by mechanika/final/generate_effects.py; edit effects.json.',
             '#pragma once', '#include <stdint.h>', 'namespace PresentationScore {',
             'struct Step { uint16_t durationMs; int8_t target; uint8_t red, green, blue; bool vibration; uint16_t toneHz; };']
    targets = {'selected': 0, 'all': -1, 'next': -2, 'previous': -3}
    for name in ('main', 'short'):
        steps = [s for s in score[name] if s.get('stage') == 'prepare']
        lines.append('constexpr Step ' + name.title() + '[] = {')
        for s in steps:
            target = targets.get(s['target'], s['target'])
            lines.append('  {%d, %d, %d, %d, %d, %s, %d},' % (
                s['duration_ms'], target, *s['light'], str(s['vibration']).lower(), s.get('tone_hz', 0)))
        lines += ['};', f'constexpr uint32_t {name.title()}PreparationMs = {sum(s["duration_ms"] for s in steps)};']
    lines += [f'constexpr uint32_t ShowMs = {score["show_ms"]};',
              f'constexpr uint16_t RevealToneHz = {score["reveal_tone_hz"]};', '}']
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generate()
    if args.check:
        if HEADER.parent.exists():
            assert HEADER.read_text(encoding='utf-8') == content, 'Stale generated PresentationScore.h'
    else:
        HEADER.write_text(content, encoding='utf-8')
