import { createHash } from 'node:crypto';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import Ajv2020 from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { parseStrictJson } from './control-validator-core.mjs';

const require = createRequire(import.meta.url);
const schemaBytes = await readFile(new URL('./control-message-v1.schema.json', import.meta.url));
const schema = parseStrictJson(schemaBytes);
const ajv = new Ajv2020({ allErrors: true, strict: true, code: { source: true, esm: true, lines: true } });
addFormats(ajv, ['uuid']);
let output = standaloneCode(ajv, ajv.compile(schema));

// Ajv standalone emits CommonJS helper references even with ESM exports.
// Convert only known pure helpers to static ESM imports; never bundle its compiler.
const helpers = new Map();
output = output.replace(/require\("([^"]+)"\)\.default/g, (_match, dependency) => {
  if (!['ajv/dist/runtime/ucs2length', 'ajv/dist/runtime/equal'].includes(dependency)) throw new Error(`Unexpected standalone dependency: ${dependency}`);
  const name = `standaloneHelper${helpers.size}`;
  if (!helpers.has(dependency)) helpers.set(dependency, name);
  return helpers.get(dependency);
});
if (/\brequire\s*\(|\beval\s*\(|\bnew\s+Function\s*\(/.test(output)) throw new Error('Generated control validator is not a static ESM module');
const digest = createHash('sha256').update(schemaBytes.toString('utf8').replaceAll('\r\n', '\n')).digest('hex');
const imports = [...helpers].map(([dependency, name]) => `import ${name}Module from '${dependency}.js';\nconst ${name} = ${name}Module.default ?? ${name}Module;`).join('\n');
output = `// Generated by generate-control-validator.mjs; do not edit.\n// control-message-v1.schema.json SHA-256: ${digest}\n// Ajv ${require('ajv/package.json').version}; strict:true, allErrors:true; uuid format.\n${imports}\n${output.trimEnd()}\n`;
const destination = new URL('./generated/control-message-v1.validator.mjs', import.meta.url);
if (process.argv.includes('--check')) {
  const actual = await readFile(destination, 'utf8').catch(() => '');
  if (actual.replaceAll('\r\n', '\n') !== output) throw new Error('Control validator drift: run npm run generate in contracts');
  console.log('Standalone control validator matches the authoritative schema and generator.');
} else {
  await mkdir(new URL('./generated/', import.meta.url), { recursive: true });
  await writeFile(destination, output);
  console.log('Generated static ESM control validator from control-message-v1.schema.json.');
}
