export const customerCopyCatalog: Readonly<Record<InterfaceLanguage, CustomerCopyCatalog>> = {
  cs: customerCopyCs,
  en: customerCopyEn,
};

export type CustomerCopyFallbackReason = 'unsupported-language' | 'missing-translation';
export type CustomerCopyResolution =
  | { readonly text: string; readonly language: InterfaceLanguage; readonly usedCzechFallback: false }
  | {
    readonly text: string;
    readonly language: 'cs';
    readonly usedCzechFallback: true;
    readonly fallbackReason: CustomerCopyFallbackReason;
  };
export type CustomerCopyParams = Readonly<Record<string, string | number>>;
export type CustomerCopyCatalogSource = Readonly<
  Partial<Record<InterfaceLanguage, Partial<Record<CustomerCopyKey, string>>>>
>;

function interpolate(template: string, params: CustomerCopyParams = {}): string {
  return template.replace(/\{\{([A-Za-z0-9_]+)\}\}/g, (placeholder, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : placeholder,
  );
}

/** Resolve a catalog entry as plain text; callers must render it with normal text bindings. */
export function resolveCustomerCopy(
  key: CustomerCopyKey,
  language: unknown,
  params: CustomerCopyParams = {},
  catalog: CustomerCopyCatalogSource = customerCopyCatalog,
): CustomerCopyResolution {
  const supportedLanguage = language === 'cs' || language === 'en' ? language : null;
  const localized = supportedLanguage ? catalog[supportedLanguage]?.[key] : undefined;
  if (supportedLanguage && typeof localized === 'string') {
    return { text: interpolate(localized, params), language: supportedLanguage, usedCzechFallback: false };
  }

  const fallbackReason = supportedLanguage ? 'missing-translation' : 'unsupported-language';
  return {
    text: interpolate(customerCopyCs[key], params),
    language: 'cs',
    usedCzechFallback: true,
    fallbackReason,
  };
}

export interface CustomerCopyAccessor {
  readonly language: ComputedRef<InterfaceLanguage>;
  resolve(key: CustomerCopyKey, params?: CustomerCopyParams): CustomerCopyResolution;
  text(key: CustomerCopyKey, params?: CustomerCopyParams): string;
}

/** Reactive accessor over the existing per-device/per-account interface preference. */
export function createCustomerCopy(
  preference: InterfaceLanguagePreference = interfaceLanguagePreference,
): CustomerCopyAccessor {
  return {
    language: computed(() => preference.language.value),
    resolve: (key, params = {}) => resolveCustomerCopy(key, preference.language.value, params),
    text: (key, params = {}) => resolveCustomerCopy(key, preference.language.value, params).text,
  };
}

export const customerCopy = createCustomerCopy();
