import hashlib
import importlib.util
import plistlib
import shutil
import tempfile
import unittest
import zipfile
from pathlib import Path


SCRIPT = Path(__file__).with_name("publish-ios-install.py")
SPEC = importlib.util.spec_from_file_location("publish_ios_install", SCRIPT)
MODULE = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(MODULE)


class PublishIosInstallTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        self.ipa = self.root / "App.ipa"
        self.checksum = self.root / "App.ipa.sha256"
        self.site = self.root / "site"
        self.site.mkdir()
        info = {
            "CFBundleIdentifier": "app.turquoise6409.green2444",
            "CFBundleShortVersionString": "1.0.0",
            "CFBundleVersion": "42",
        }
        with zipfile.ZipFile(self.ipa, "w") as archive:
            archive.writestr("Payload/App.app/Info.plist", plistlib.dumps(info))
        self.digest = hashlib.sha256(self.ipa.read_bytes()).hexdigest()
        self.checksum.write_text(f"{self.digest}  dist/ipa/App.ipa\n", encoding="ascii")

    def publish(self):
        return MODULE.publish(
            self.ipa,
            self.checksum,
            self.site,
            "dildovander.de",
            "123-1",
            "app.turquoise6409.green2444",
        )

    def test_publishes_manifest_page_and_unchanged_ipa(self):
        self.assertEqual("https://dildovander.de/ios/", self.publish())
        release = self.site / "releases" / "123-1"
        self.assertEqual(self.ipa.read_bytes(), (release / "kufr.ipa").read_bytes())
        manifest = plistlib.loads((release / "manifest.plist").read_bytes())
        item = manifest["items"][0]
        self.assertEqual(
            "https://dildovander.de/ios/releases/123-1/kufr.ipa",
            item["assets"][0]["url"],
        )
        self.assertEqual("app.turquoise6409.green2444",
                         item["metadata"]["bundle-identifier"])
        self.assertEqual("42", item["metadata"]["bundle-version"])
        page = (self.site / "index.html").read_text(encoding="utf-8")
        self.assertIn("itms-services://?action=download-manifest", page)
        self.assertIn("https%3A%2F%2Fdildovander.de%2Fios%2Freleases%2F123-1%2Fmanifest.plist", page)
        self.assertIn("Verze 1.0.0 · sestavení 42", page)

    def test_rejects_url_injection_and_private_addresses(self):
        for host in ("https://dildovander.de", "dildovander.de/path", "dildovander.de@evil.test", "127.0.0.1", "bad host"):
            with self.subTest(host=host), self.assertRaises(ValueError):
                MODULE.publish(self.ipa, self.checksum, self.site, host, "124-1", "app.turquoise6409.green2444")
        self.assertFalse((self.site / "releases").exists())

    def test_rejects_bad_checksum_before_publishing(self):
        self.checksum.write_text("0" * 64 + "  App.ipa\n", encoding="ascii")
        with self.assertRaisesRegex(ValueError, "checksum does not match"):
            self.publish()
        self.assertFalse((self.site / "releases").exists())

    def test_rejects_empty_checksum(self):
        self.checksum.write_text("", encoding="ascii")
        with self.assertRaisesRegex(ValueError, "Invalid IPA checksum"):
            self.publish()

    def test_rejects_existing_release(self):
        self.publish()
        with self.assertRaisesRegex(ValueError, "already published"):
            self.publish()

    def test_archive_embeds_canonical_components_without_runtime_asset_dependencies(self):
        page = MODULE.render_page("1.0.0", "42", "https://example.invalid/manifest.plist",
                                  "https://example.invalid/kufr.ipa")
        self.assertIn('class="aw-root"', page)
        self.assertIn('class="aw-card install-card"', page)
        self.assertIn('class="aw-button aw-button--primary install-action"', page)
        self.assertIn('.aw-button', MODULE.INSTALLER_DESIGN_CSS)
        self.assertIn('--aw-font-ui:', MODULE.INSTALLER_DESIGN_CSS)
        self.assertIn('Generated by scripts/generate_design_tokens.py', MODULE.INSTALLER_DESIGN_CSS)
        self.assertNotIn('@import', MODULE.INSTALLER_DESIGN_CSS)
        self.assertNotIn('@font-face', MODULE.INSTALLER_DESIGN_CSS)
        self.assertIn('system', MODULE.INSTALLER_DESIGN_CSS)
        self.assertGreater(len(MODULE.INSTALLER_DESIGN_CSS), 1000)
        self.assertLess(len(MODULE.INSTALLER_DESIGN_CSS), 100_000)
        self.assertIn(f'content="{MODULE.INSTALLER_THEME_COLOR}"', page)

    def test_publisher_still_runs_when_only_its_script_is_copied_to_private_helper(self):
        script = self.root / "isolated" / "publish-ios-install.py"
        script.parent.mkdir()
        shutil.copyfile(SCRIPT, script)
        spec = importlib.util.spec_from_file_location("isolated_publish_ios_install", script)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        page = module.render_page("1.0.0", "42", "https://example.invalid/manifest.plist",
                                  "https://example.invalid/kufr.ipa")
        self.assertIn(MODULE.INSTALLER_DESIGN_CSS, page)
        self.assertIn("Verze 1.0.0 · sestavení 42", page)

    def test_rendering_escapes_metadata_and_preserves_encoded_install_manifest(self):
        page = MODULE.render_page('<v1>', '42 & 43',
                                  'https://example.invalid/manifest.plist?name="test"&v=1',
                                  'https://example.invalid/kufr.ipa?name="test"&v=1')
        self.assertIn('Verze &lt;v1&gt; · sestavení 42 &amp; 43', page)
        self.assertIn('name%3D%22test%22%26v%3D1', page)
        self.assertIn('kufr.ipa?name=&quot;test&quot;&amp;v=1', page)
        self.assertNotIn('Verze <v1>', page)


if __name__ == "__main__":
    unittest.main()
